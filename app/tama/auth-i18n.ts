export function translateAuthMessage(lang: TamaLang, raw: unknown, fallbackKey = "genericServerError"): string {
  const msg = typeof raw === "string" ? raw.trim() : "";
  if (!msg) return authText(lang, fallbackKey);
  if (lang === "hu") return msg;
  for (const [re, en] of MESSAGES_EN) {
    if (re.test(msg)) return en;
  }
  if (/^[\x20-\x7E]+$/.test(msg) && !/\b(kérj|jelszó|fiók|hiba|link)\b/i.test(msg)) return msg;
  return authText(lang, fallbackKey);
}
