const HU_TO_EN = new Map(IBUSZ_MESSAGES.map((m) => [m.hu, m.en]));

const HU_CHARS = /[áéíóöőúüűÁÉÍÓÖŐÚÜŰ]/;

/** Server message -> portal language. Hungarian passes through, English maps by exact pair. */
export function translateIbuszMessage(
  lang: "hu" | "en",
  message: string | undefined | null,
  fallback: string,
): string {
  const msg = String(message || "").trim();
  if (!msg) return fallback;
  if (lang === "hu") return msg;
  const en = HU_TO_EN.get(msg);
  if (en) return en;
  if (HU_CHARS.test(msg)) return fallback;
  return msg;
}
